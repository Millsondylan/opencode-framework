#!/usr/bin/env python3
"""Screenshot compositor for Play Store ready marketing imagery.

This module stitches REAL UI screenshots (captured from running Flutter
applications on emulators or physical devices) into Claude-generated
device frames and backgrounds. The compositor never synthesises UI.
Frames, background gradients, and locale caption text MAY be produced
by a generative model; the application screen itself MUST come from
`integration_test` golden runs under `screenshots/flows/`.

Pipeline:
    1. Emulator boots via emulator_matrix.py
    2. Flutter driver captures golden screens -> PNG files
    3. This compositor resizes each golden into a device frame
    4. Frame is overlaid on a marketing background at the Play Store
       mandatory resolution for that form factor

Play Store 2026 asset sizing reference (portrait):
    * Phone:       1080 x 1920
    * 7in Tablet:  1200 x 1920
    * 10in Tablet: 1600 x 2560

Usage (library):
    >>> spec = DEVICE_SPECS["phone_pixel8"]
    >>> comp = FrameCompositor(spec)
    >>> comp.compose("ui.png", "bg.png", "out.png", "Welcome")

Usage (CLI):
    python compositor.py \\
        --form-factor phone \\
        --ui captures/phone_01_home.png \\
        --bg backgrounds/teal.png \\
        --out playstore/phone_01.png \\
        --caption "Track spending instantly"
"""

from __future__ import annotations

import argparse
import os
import sys
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

try:
    from PIL import Image, ImageDraw, ImageFont

    PIL_AVAILABLE = True
    PIL_IMPORT_ERROR: Optional[str] = None
except ImportError as exc:
    PIL_AVAILABLE = False
    PIL_IMPORT_ERROR = str(exc)
    Image = None  # type: ignore
    ImageDraw = None  # type: ignore
    ImageFont = None  # type: ignore


# Play Store mandatory dimensions (width, height) in portrait orientation.
PLAY_STORE_SIZES: Dict[str, Tuple[int, int]] = {
    "phone": (1080, 1920),
    "tablet7": (1200, 1920),
    "tablet10": (1600, 2560),
}

# Minimum and maximum screenshots permitted per form factor.
MIN_SCREENSHOTS_PER_FORM_FACTOR = 2
MAX_SCREENSHOTS_PER_FORM_FACTOR = 8


@dataclass(frozen=True)
class DeviceSpec:
    """Physical device frame descriptor for a single form factor."""

    name: str
    width: int
    height: int
    frame_image_path: str
    # Rectangle inside the frame PNG where the real UI goes.
    # Tuple form: (left, top, inner_width, inner_height) in pixels.
    frame_content_box: Tuple[int, int, int, int]
    form_factor: str

    def content_region(self) -> Tuple[int, int, int, int]:
        """Return the PIL paste box (left, top, right, bottom)."""
        left, top, inner_w, inner_h = self.frame_content_box
        return (left, top, left + inner_w, top + inner_h)


@dataclass
class CompositionConfig:
    """Inputs for a single composited marketing image."""

    device_spec: DeviceSpec
    ui_path: str
    bg_path: str
    output_path: str
    locale_caption: Optional[str] = None
    caption_color: Tuple[int, int, int] = (255, 255, 255)
    caption_y: int = 80


# Canonical device specifications for the three supported form factors.
# Frame images are generated by a separate Claude image pass and dropped in
# `screenshots/frames/`. Content boxes are tuned for the 2026 device frames.
DEVICE_SPECS: Dict[str, DeviceSpec] = {
    "phone_pixel8": DeviceSpec(
        name="Pixel 8",
        width=1080,
        height=1920,
        frame_image_path="screenshots/frames/pixel8_frame.png",
        frame_content_box=(60, 180, 960, 1560),
        form_factor="phone",
    ),
    "tablet7_nexus7": DeviceSpec(
        name="Nexus 7",
        width=1200,
        height=1920,
        frame_image_path="screenshots/frames/nexus7_frame.png",
        frame_content_box=(70, 200, 1060, 1520),
        form_factor="tablet7",
    ),
    "tablet10_pixel_tablet": DeviceSpec(
        name="Pixel Tablet",
        width=1600,
        height=2560,
        frame_image_path="screenshots/frames/pixel_tablet_frame.png",
        frame_content_box=(80, 260, 1440, 2040),
        form_factor="tablet10",
    ),
}


class CompositorError(RuntimeError):
    """Raised for unrecoverable composition failures."""


def _require_pil() -> None:
    """Abort cleanly when Pillow is absent."""
    if not PIL_AVAILABLE:
        raise CompositorError(
            "Pillow is required for the compositor. "
            f"Install with 'pip install Pillow' (import error: {PIL_IMPORT_ERROR})."
        )


class FrameCompositor:
    """Composites real UI captures into device frames on top of backgrounds."""

    def __init__(self, device_spec: DeviceSpec) -> None:
        self.device_spec = device_spec

    def compose(
        self,
        ui_image_path: str,
        bg_image_path: str,
        output_path: str,
        locale_caption: Optional[str] = None,
    ) -> str:
        """Build a single Play Store asset and return its output path."""
        _require_pil()
        self._validate_input_path(ui_image_path, "UI screenshot")
        self._validate_input_path(bg_image_path, "background image")

        spec = self.device_spec
        canvas = self._prepare_background(bg_image_path, spec.width, spec.height)
        frame = self._open_frame(spec.frame_image_path, spec.width, spec.height)
        ui_img = self._open_ui(ui_image_path, spec.frame_content_box)

        # Paste UI into frame at the content region.
        left, top, inner_w, inner_h = spec.frame_content_box
        frame_with_ui = frame.copy()
        frame_with_ui.paste(ui_img, (left, top), ui_img if ui_img.mode == "RGBA" else None)

        # Paste frame (with UI) on the background.
        canvas.paste(frame_with_ui, (0, 0), frame_with_ui if frame_with_ui.mode == "RGBA" else None)

        if locale_caption:
            self._draw_caption(canvas, locale_caption)

        self._ensure_parent_dir(output_path)
        canvas.save(output_path, format="PNG", optimize=True)
        return output_path

    def validate_play_store_size(
        self, output_path: str, form_factor: str
    ) -> Tuple[bool, str]:
        """Check that the produced PNG matches Play Store required pixels."""
        _require_pil()
        if form_factor not in PLAY_STORE_SIZES:
            return (
                False,
                f"Unknown form factor '{form_factor}'. "
                f"Valid: {sorted(PLAY_STORE_SIZES.keys())}",
            )
        expected_w, expected_h = PLAY_STORE_SIZES[form_factor]
        if not os.path.isfile(output_path):
            return (False, f"Output file missing: {output_path}")
        with Image.open(output_path) as img:
            actual = img.size
        if actual != (expected_w, expected_h):
            return (
                False,
                f"Size mismatch for {form_factor}: got {actual}, "
                f"expected ({expected_w}, {expected_h})",
            )
        return (True, f"OK: {form_factor} at {actual[0]}x{actual[1]}")

    # ------------------------------------------------------------------
    # Internals
    # ------------------------------------------------------------------
    @staticmethod
    def _validate_input_path(path: str, label: str) -> None:
        if not path:
            raise CompositorError(f"{label} path is empty")
        if not os.path.isfile(path):
            raise CompositorError(f"{label} not found at '{path}'")

    @staticmethod
    def _ensure_parent_dir(path: str) -> None:
        parent = os.path.dirname(os.path.abspath(path))
        if parent and not os.path.isdir(parent):
            os.makedirs(parent, exist_ok=True)

    @staticmethod
    def _prepare_background(bg_path: str, target_w: int, target_h: int):
        bg = Image.open(bg_path).convert("RGBA")
        if bg.size != (target_w, target_h):
            bg = bg.resize((target_w, target_h), Image.LANCZOS)
        return bg

    @staticmethod
    def _open_frame(frame_path: str, target_w: int, target_h: int):
        if not os.path.isfile(frame_path):
            # Fallback: a blank transparent frame so compositor still runs.
            frame = Image.new("RGBA", (target_w, target_h), (0, 0, 0, 0))
            return frame
        frame = Image.open(frame_path).convert("RGBA")
        if frame.size != (target_w, target_h):
            frame = frame.resize((target_w, target_h), Image.LANCZOS)
        return frame

    @staticmethod
    def _open_ui(ui_path: str, content_box: Tuple[int, int, int, int]):
        _, _, inner_w, inner_h = content_box
        if inner_w <= 0 or inner_h <= 0:
            raise CompositorError(
                f"Frame content box has non positive dimensions: {content_box}"
            )
        ui = Image.open(ui_path).convert("RGBA")
        # Preserve aspect ratio while filling the inner area, then centre-crop.
        src_w, src_h = ui.size
        if src_w == 0 or src_h == 0:
            raise CompositorError("UI screenshot has zero dimension")
        src_ratio = src_w / src_h
        tgt_ratio = inner_w / inner_h
        if abs(src_ratio - tgt_ratio) < 0.01:
            return ui.resize((inner_w, inner_h), Image.LANCZOS)
        if src_ratio > tgt_ratio:
            new_h = inner_h
            new_w = int(new_h * src_ratio)
        else:
            new_w = inner_w
            new_h = int(new_w / src_ratio)
        scaled = ui.resize((new_w, new_h), Image.LANCZOS)
        off_x = max(0, (new_w - inner_w) // 2)
        off_y = max(0, (new_h - inner_h) // 2)
        return scaled.crop((off_x, off_y, off_x + inner_w, off_y + inner_h))

    def _draw_caption(self, canvas, caption: str) -> None:
        if not caption or not caption.strip():
            return
        draw = ImageDraw.Draw(canvas)
        font = self._load_caption_font()
        # Approximate text box so we can centre it along the top.
        try:
            bbox = draw.textbbox((0, 0), caption, font=font)
            text_w = bbox[2] - bbox[0]
        except Exception:
            text_w = len(caption) * 28
        x = max(0, (self.device_spec.width - text_w) // 2)
        draw.text((x, 80), caption, fill=(255, 255, 255, 255), font=font)

    @staticmethod
    def _load_caption_font():
        # Try a common system font; fall back to PIL default bitmap font.
        candidates = [
            "/System/Library/Fonts/Supplemental/Arial.ttf",
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
        ]
        for path in candidates:
            if os.path.isfile(path):
                try:
                    return ImageFont.truetype(path, 64)
                except Exception:
                    continue
        return ImageFont.load_default()


def batch_compose(configs: List[CompositionConfig]) -> List[str]:
    """Run every composition in sequence and return output paths."""
    _require_pil()
    outputs: List[str] = []
    errors: List[str] = []
    for cfg in configs:
        compositor = FrameCompositor(cfg.device_spec)
        try:
            out = compositor.compose(
                cfg.ui_path,
                cfg.bg_path,
                cfg.output_path,
                cfg.locale_caption,
            )
            outputs.append(out)
        except CompositorError as exc:
            errors.append(f"{cfg.output_path}: {exc}")
    if errors:
        joined = "; ".join(errors)
        raise CompositorError(f"batch_compose had {len(errors)} failures: {joined}")
    return outputs


def enforce_count_rules(form_factor: str, count: int) -> Tuple[bool, str]:
    """Validate that we are within Play Store min/max per form factor."""
    if count < MIN_SCREENSHOTS_PER_FORM_FACTOR:
        return (
            False,
            f"{form_factor}: only {count} screenshot(s); "
            f"min is {MIN_SCREENSHOTS_PER_FORM_FACTOR}.",
        )
    if count > MAX_SCREENSHOTS_PER_FORM_FACTOR:
        return (
            False,
            f"{form_factor}: {count} screenshots exceeds max of "
            f"{MAX_SCREENSHOTS_PER_FORM_FACTOR}.",
        )
    return (True, f"{form_factor}: {count} screenshots within limits.")


# ----------------------------------------------------------------------
# CLI
# ----------------------------------------------------------------------
def _resolve_spec(form_factor: str) -> DeviceSpec:
    mapping = {
        "phone": DEVICE_SPECS["phone_pixel8"],
        "tablet7": DEVICE_SPECS["tablet7_nexus7"],
        "tablet10": DEVICE_SPECS["tablet10_pixel_tablet"],
    }
    if form_factor not in mapping:
        raise CompositorError(
            f"Unknown form factor '{form_factor}'. "
            f"Valid: {sorted(mapping.keys())}"
        )
    return mapping[form_factor]


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Composite real UI screenshots into Play Store assets."
    )
    parser.add_argument(
        "--form-factor",
        required=True,
        choices=sorted(PLAY_STORE_SIZES.keys()),
    )
    parser.add_argument("--ui", required=True, help="Path to real UI screenshot")
    parser.add_argument("--bg", required=True, help="Path to background image")
    parser.add_argument("--out", required=True, help="Output PNG path")
    parser.add_argument("--caption", default=None, help="Optional locale caption")
    parser.add_argument(
        "--skip-validate",
        action="store_true",
        help="Skip Play Store size validation",
    )
    ns = parser.parse_args(argv)

    try:
        spec = _resolve_spec(ns.form_factor)
        compositor = FrameCompositor(spec)
        out = compositor.compose(ns.ui, ns.bg, ns.out, ns.caption)
        print(f"Wrote {out}")
        if not ns.skip_validate:
            ok, msg = compositor.validate_play_store_size(out, ns.form_factor)
            print(msg)
            if not ok:
                return 2
    except CompositorError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
